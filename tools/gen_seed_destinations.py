"""Generate database/seed_destinations.sql from seed_data.py.

The SQL is safe to re-run: existing cities/places/risks are matched by name
and not duplicated, and admin edits to places are not overwritten.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from seed_data import COUNTRIES, RISKS, VISAS_FOR_THAI, CITIES, PLACES, SAFETY  # noqa: E402

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "seed_destinations.sql")


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def country_id(iso):
    return f"(SELECT id FROM rj_countries WHERE iso2 = {q(iso)})"


def city_id(name):
    return f"(SELECT id FROM rj_cities WHERE name_en = {q(name)})"


def place_id(name):
    return f"(SELECT id FROM rj_places WHERE name_en = {q(name)} LIMIT 1)"


city_names = {c[1] for c in CITIES}
place_names = [p["name_en"] for p in PLACES]
assert len(place_names) == len(set(place_names)), "duplicate place names"
for p in PLACES:
    assert p["city"] in city_names, p["city"]
for s in SAFETY:
    assert s[0] in place_names, s[0]

out = [
    "-- Random Journey: destination content (5 countries, cities, places, risks, visas)",
    "-- Generated by tools/gen_seed_destinations.py. Safe to re-run; existing rows are kept.",
    "-- Prices are typical local-currency amounts. Verify prices, hours and visa rules before presenting.",
    "SET NAMES utf8mb4;",
    "",
    "-- Countries ------------------------------------------------------------",
]
for iso, c in COUNTRIES.items():
    sets = ",\n    ".join(f"{k} = {q(v)}" for k, v in c.items())
    out.append(f"UPDATE rj_countries SET is_destination = 1,\n    {sets}\nWHERE iso2 = {q(iso)};")

out += ["", "-- Cities ---------------------------------------------------------------"]
for iso, name, name_th, lat, lng, env, cost, season, summary, history in CITIES:
    out.append(
        "INSERT INTO rj_cities (country_id, name_en, name_th, lat, lng, environment, cost_index, best_season, summary, history)\n"
        f"VALUES ({country_id(iso)}, {q(name)}, {q(name_th)}, {lat}, {lng}, {q(env)}, {q(cost)}, {q(season)}, {q(summary)}, {q(history)})\n"
        "AS new ON DUPLICATE KEY UPDATE name_th = new.name_th, lat = new.lat, lng = new.lng, environment = new.environment,\n"
        "    cost_index = new.cost_index, best_season = new.best_season, summary = new.summary, history = new.history;"
    )

cols = ["name_en", "name_th", "summary", "description", "history", "culture_beliefs", "how_to_get_there", "address",
        "lat", "lng", "price_level", "price_min", "price_max", "environment", "terrain", "is_historical", "difficulty",
        "duration_hours", "permit_required", "permit_info", "opening_hours", "dress_code"]
out += ["", "-- Places (skipped if a place with the same name already exists in the city) ----"]
for p in PLACES:
    values = ", ".join(q(p[c]) for c in cols)
    out.append(
        f"INSERT INTO rj_places (city_id, category_id, {', '.join(cols)}, status)\n"
        f"SELECT {city_id(p['city'])}, (SELECT id FROM rj_categories WHERE slug = {q(p['cat'])}), {values}, 'published'\n"
        f"FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM rj_places WHERE name_en = {q(p['name_en'])} AND city_id = {city_id(p['city'])});"
    )
    if p["tags"]:
        slugs = ", ".join(q(t) for t in p["tags"])
        out.append(
            "INSERT IGNORE INTO rj_place_tags (place_id, tag_id)\n"
            f"SELECT {place_id(p['name_en'])}, id FROM rj_tags WHERE slug IN ({slugs});"
        )

out += ["", "-- Risk scores (country-wide) ------------------------------------------------"]
for iso, rows in RISKS.items():
    for risk_type, score, desc, handle in rows:
        out.append(
            "INSERT INTO rj_risk_scores (country_id, city_id, risk_type, score, description, how_to_handle, source_url)\n"
            f"SELECT {country_id(iso)}, NULL, {q(risk_type)}, {score}, {q(desc)}, {q(handle)}, 'https://travel.state.gov/traveladvisories'\n"
            f"FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM rj_risk_scores WHERE country_id = {country_id(iso)} AND city_id IS NULL AND risk_type = {q(risk_type)});"
        )

out += ["", "-- Place safety tips -----------------------------------------------------------"]
for place, risk_type, title, tip in SAFETY:
    out.append(
        "INSERT INTO rj_place_safety (place_id, risk_type, title, tip)\n"
        f"SELECT {place_id(place)}, {q(risk_type)}, {q(title)}, {q(tip)}\n"
        f"FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM rj_place_safety WHERE place_id = {place_id(place)} AND title = {q(title)});"
    )

out += ["", "-- Visa rules for Thai passport holders ---------------------------------------"]
for iso, v in VISAS_FOR_THAI.items():
    out.append(
        "INSERT INTO rj_visa_rules (nationality_country_id, destination_country_id, visa_type, max_stay_days, fee_text, summary, how_to_apply, official_url, verified_at)\n"
        f"VALUES ({country_id('TH')}, {country_id(iso)}, {q(v['visa_type'])}, {q(v['max_stay_days'])}, {q(v['fee_text'])}, "
        f"{q(v['summary'])}, {q(v['how_to_apply'])}, {q(v['official_url'])}, {q(v['verified_at'])})\n"
        "AS new ON DUPLICATE KEY UPDATE visa_type = new.visa_type, max_stay_days = new.max_stay_days, fee_text = new.fee_text,\n"
        "    summary = new.summary, how_to_apply = new.how_to_apply, official_url = new.official_url, verified_at = new.verified_at;"
    )

OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{OUT}: {len(COUNTRIES)} countries, {len(CITIES)} cities, {len(PLACES)} places, "
      f"{sum(len(r) for r in RISKS.values())} risks, {len(SAFETY)} safety tips, {len(VISAS_FOR_THAI)} visa rules")
