"""Generate database/seed_photos.sql from tools/photos.json.

photos.json is collected from the Wikipedia / Wikimedia Commons APIs (see
tools/fetch_photos.js) and holds, per place name:
    {"wiki": "https://en.wikipedia.org/wiki/...", "photos": [[file, width, height, author, license], ...]}

Only links and credits are stored; the images stay on Wikimedia's servers.
The SQL is safe to re-run: photos already present are skipped.

Usage: python3 tools/gen_seed_photos.py database/seed_photos.sql
"""
import hashlib
import json
import sys
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).parent
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "seed_photos.sql")
DATA = json.loads((HERE / "photos.json").read_text(encoding="utf-8"))

LICENSES = {
    "CC0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "Public domain": None,
    "CC BY 2.0": "https://creativecommons.org/licenses/by/2.0/",
    "CC BY 2.5": "https://creativecommons.org/licenses/by/2.5/",
    "CC BY 3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC BY 4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC BY-SA 2.0": "https://creativecommons.org/licenses/by-sa/2.0/",
    "CC BY-SA 2.5": "https://creativecommons.org/licenses/by-sa/2.5/",
    "CC BY-SA 3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
    "CC BY-SA 4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
}


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def commons_urls(file_title: str, width: int):
    """Thumbnail URLs on upload.wikimedia.org, built the way MediaWiki builds them."""
    name = file_title.removeprefix("File:").replace(" ", "_")
    digest = hashlib.md5(name.encode("utf-8")).hexdigest()
    path = f"{digest[0]}/{digest[:2]}/{quote(name)}"
    base = "https://upload.wikimedia.org/wikipedia/commons"
    big = f"{base}/thumb/{path}/1280px-{quote(name)}" if width >= 1280 else f"{base}/{path}"
    thumb = f"{base}/thumb/{path}/500px-{quote(name)}"
    page = "https://commons.wikimedia.org/wiki/" + quote(f"File:{name}")
    return big, thumb, page


out = [
    "-- Random Journey: photos of places (links and credits from Wikimedia Commons)",
    "-- Generated by tools/gen_seed_photos.py. Safe to re-run; existing photos are kept.",
    "SET NAMES utf8mb4;",
    "",
]
count = 0
for place, entry in DATA.items():
    pid = f"(SELECT id FROM rj_places WHERE name_en = {q(place)} LIMIT 1)"
    if entry.get("wiki"):
        out.append(f"UPDATE rj_places SET wiki_url = COALESCE(wiki_url, {q(entry['wiki'])}) WHERE name_en = {q(place)};")
    for order, (file_title, width, height, author, lic) in enumerate(entry.get("photos", [])):
        big, thumb, page = commons_urls(file_title, width)
        w, h = (1280, round(height * 1280 / width)) if width >= 1280 else (width, height)
        out.append(
            "INSERT IGNORE INTO rj_photos (place_id, url, thumb_url, width, height, caption, author, license, license_url, source_url, sort_order)\n"
            f"SELECT {pid}, {q(big)}, {q(thumb)}, {w}, {h}, NULL, {q(author)}, {q(lic)}, "
            f"{q(LICENSES.get(lic or ''))}, {q(page)}, {order}\nFROM DUAL WHERE {pid} IS NOT NULL;"
        )
        count += 1

OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{OUT}: {count} photos for {sum(1 for e in DATA.values() if e.get('photos'))} places")
